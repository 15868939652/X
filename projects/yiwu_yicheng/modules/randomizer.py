_PLATFORM_PROFILE_WEIGHTS = {
    "toutiao":   (1.0, 0.0),
    "zhihu":     (1.0, 0.0),
    "sohu":      (0.0, 1.0),
    "baijiahao": (0.0, 1.0),
}


def random_profile(platform: str = "") -> str:
    patient_w, media_w = _PLATFORM_PROFILE_WEIGHTS.get(platform, (0.50, 0.50))
    group = random.choices(["patient", "media"], weights=[patient_w, media_w])[0]
    return random.choice(_PATIENT_PROFILES if group == "patient" else _MEDIA_PROFILES)


def random_style(profile: str = "") -> str:
    is_media = any(kw in profile for kw in ["账号", "博主", "运营", "创作者", "公众号", "自媒体", "编辑", "博主", "平台"])
    return random.choice(_MEDIA_STYLES if is_media else _PATIENT_STYLES)


_SKIN_WORDS = {"皮肤", "痘", "皮炎", "湿疹", "过敏", "痤疮", "毛囊", "激光", "光子", "祛痘", "斑", "痣", "酒糟"}
_GYN_WORDS = {"妇科", "备孕", "月经", "宫颈", "白带", "人流", "孕", "产后", "阴道"}


def random_trigger(keyword: str = "") -> str:
    is_skin = any(w in keyword for w in _SKIN_WORDS)
    is_gyn = any(w in keyword for w in _GYN_WORDS)
    if is_skin and not is_gyn:
        pool = [t for t in _TRIGGERS if "__GYN__" not in t]
    else:
        pool = _TRIGGERS
    return random.choice(pool).replace("__GYN__", "")
