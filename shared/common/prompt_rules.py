def resolve_title_rule(variant: str, platform: str, mode: str, brand: str) -> str:
    platform_key = platform if platform in {"sohu", "baijiahao"} else "generic"
    mode_key = "exp" if mode == "exp" else "default"
    template = TITLE_RULES[variant][(platform_key, mode_key)]
    return template.substitute(brand=brand)
